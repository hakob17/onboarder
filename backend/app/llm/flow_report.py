"""Flow report: pick an endpoint, trace it end-to-end (across projects), and produce a
shareable Markdown document — an AI narrative of the flow (when a key / local CLI is
configured) plus the grounded step list with file:line evidence. The frontend renders it
and offers Download .md / Save as PDF."""

from ..config import llm_enabled
from ..db import get_conn


def _lookup(workspace_id: str, ids: list[str]) -> dict[str, dict]:
    if not ids:
        return {}
    conn = get_conn()
    try:
        ph = ",".join("?" * len(ids))
        rows = conn.execute(
            f"SELECT n.id, n.kind, n.name, n.file, n.line_start, n.project_id, p.name AS project"
            f" FROM nodes n LEFT JOIN projects p ON p.id = n.project_id"
            f" WHERE n.workspace_id = ? AND n.id IN ({ph})",
            (workspace_id, *ids)).fetchall()
    finally:
        conn.close()
    return {r["id"]: dict(r) for r in rows}


def generate_flow_report(workspace_id: str, from_id: str | None = None,
                         node_ids: list[str] | None = None, title: str | None = None) -> dict:
    ordered: list[str] = []
    seen: set[str] = set()
    if node_ids:
        # an explicit flow (e.g. the nodes the chat found for "how does OTP work?")
        for nid in node_ids:
            if nid not in seen:
                seen.add(nid)
                ordered.append(nid)
    else:
        from ..analysis.graph import trace
        for path in sorted(trace(workspace_id, from_id, None, max_depth=12), key=len, reverse=True):
            for nid in path:
                if nid not in seen:
                    seen.add(nid)
                    ordered.append(nid)
        if from_id and from_id not in seen:
            ordered.insert(0, from_id)
    details = _lookup(workspace_id, ordered)
    ordered = [n for n in ordered if n in details]
    if not ordered:
        raise ValueError("no nodes found for this flow")

    heading = title or details[ordered[0]]["name"]

    def _short(d: dict) -> str:
        proj = (d.get("project") or "").split("/")[-1]
        return f"{d['kind']}: {d['name']}" + (f" [{proj}]" if proj else "")

    narrative = ""
    if llm_enabled():
        try:
            from .provider import text
            body = "\n".join(f"- {_short(details[n])}"
                             + (f" ({details[n]['file']}:{details[n]['line_start']})" if details[n].get("file") else "")
                             for n in ordered)
            prompt = (
                "You are onboarding a developer. Explain this request flow through the codebase: "
                "business meaning first, then mechanics, in 2 short plain-language paragraphs. "
                "Ground every claim in the steps below — do not invent anything, do not restate the list.\n\n"
                f"Flow (in order):\n{body}")
            narrative = (text(prompt) or "").strip()
        except Exception:
            narrative = ""

    lines = [f"# Flow — {heading}", ""]
    if narrative:
        lines += [narrative, ""]
    projects = [p.split("/")[-1] for p in dict.fromkeys(details[n].get("project") for n in ordered) if p]
    if len(projects) > 1:
        lines += [f"**Spans {len(projects)} projects:** " + ", ".join(projects), ""]
    lines += [f"## Flow steps ({len(ordered)})", ""]
    for i, nid in enumerate(ordered, 1):
        d = details[nid]
        proj = (d.get("project") or "").split("/")[-1]
        loc = f" — `{d['file']}:{d['line_start']}`" if d.get("file") else ""
        tag = f" · _{proj}_" if proj else ""
        lines.append(f"{i}. **{d['name']}** — {d['kind']}{tag}{loc}")
    lines += ["", "---", "_Generated by Onboarder from static analysis; every step is evidence-linked._"]

    return {"title": f"Flow — {heading}", "markdown": "\n".join(lines),
            "node_ids": ordered, "has_ai": bool(narrative)}
